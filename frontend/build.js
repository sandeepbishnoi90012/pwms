// Build step for static hosting (Render Static Site, Netlify, Cloudflare Pages, GitHub Pages...).
// 1. copies the React libraries into public/vendor
// 2. if env PWMS_API is set (e.g. https://pwms-backend.onrender.com/api) writes it into public/config.js
const fs = require('fs');
const path = require('path');

const nm = p => path.join(__dirname, 'node_modules', p);
const vendor = path.join(__dirname, 'public', 'vendor');
fs.mkdirSync(vendor, { recursive: true });
fs.copyFileSync(nm('react/umd/react.development.js'), path.join(vendor, 'react.js'));
fs.copyFileSync(nm('react-dom/umd/react-dom.development.js'), path.join(vendor, 'react-dom.js'));
fs.copyFileSync(nm('htm/dist/htm.js'), path.join(vendor, 'htm.js'));

if (process.env.PWMS_API) {
  let api = process.env.PWMS_API.trim().replace(/\/+$/, '');
  if (!/\/api$/.test(api)) api += '/api';
  fs.writeFileSync(path.join(__dirname, 'public', 'config.js'),
    `// Generated by build.js from the PWMS_API environment variable\nwindow.PWMS_API = ${JSON.stringify(api)};\n`);
  console.log('API URL set to', api);
} else {
  console.log('PWMS_API not set - keeping public/config.js as is');
}
console.log('Frontend build done -> public/');
